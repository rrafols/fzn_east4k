GLYPHS = {c: [r for r in v.split(' ')] for c, v in _G.items()}

def draw(put, x, y, text, colour, scale=1):
    """put(px, py, rgb) for each lit pixel."""
    for ch in str(text):
        g = GLYPHS.get(ch.upper())
        if g:
            for ry, row in enumerate(g):
                for rx, p in enumerate(row):
                    if p == '#':
                        for sy in range(scale):
                            for sx in range(scale):
                                put(x + rx*scale + sx, y + ry*scale + sy, colour)
        x += 6 * scale
    return x
